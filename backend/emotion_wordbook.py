EMOTION_WORD_TO_CATEGORY: dict[str, str] = {}
for _category, _words in EMOTION_CATEGORIES.items():
    for _word in _words:
        # 같은 단어가 여러 대분류에 중복 등장하면(예: "가벼운") 먼저 나온 대분류를 우선한다 -
        # frontend WORD_TO_CATEGORY와 같은 규칙(EMOTION_CATEGORIES 선언 순서 우선).
        EMOTION_WORD_TO_CATEGORY.setdefault(_word, _category)


def genus_for_word(word: str) -> str | None:
    """깊이 모드에서 고른 단어 -> 속. 단어장에 없으면 None(호출부가 AI 커스텀 분류로 넘긴다)."""
    category = EMOTION_WORD_TO_CATEGORY.get(word)
    return EMOTION_CATEGORY_TO_GENUS.get(category) if category else None


def genus_for_word_or_category(word: str, category: str | None = None) -> str | None:
    """genus_for_word의 확장판 - 프론트가 "실제로 어느 대분류 아코디언에서 골랐는지" 힌트를
    함께 보내면(category) 그걸 우선한다. "고통스러운"/"구역질나는"처럼 같은 단어가 분노/미움
    둘 다에 실재하는 경우, 힌트 없이는 EMOTION_WORD_TO_CATEGORY의 배열 순서 우선 규칙(항상
    분노/격동으로 귀결)에 기댈 수밖에 없어 사용자가 미움에서 골라도 항상 격동 꽃이 피는
    불일치가 있었다. category 힌트가 없거나(레거시로 저장된 기록) 단어장에 없는 값이면
    기존 genus_for_word로 조용히 폴백한다."""
    if category and category in EMOTION_CATEGORY_TO_GENUS:
        return EMOTION_CATEGORY_TO_GENUS[category]
    return genus_for_word(word)


