# 7개 대분류 -> 8속(2차 확장: 기존 5속에서 3개 감정을 분리 독립). frontend/src/lib/
# emotionWordbook.ts의 EMOTION_CATEGORY_TO_GENUS와 근거/주석까지 동일하게 맞춘다 - 몽환은
# 이 표의 목적지가 되지 않는다(원본 워크시트에 "혼란/놀람" 계열 대분류가 없어, 여기 없는
# 단어는 _classify_custom_genus AI 폴백으로 넘어간다).
#
# 1차 설계(온기<-기쁨+사랑, 격동<-분노+미움, 여운<-슬픔+바램)에서는 대분류 2개씩을 억지로
# 하나의 기존 속에 욱여넣었었다 - 이제 그 중 "기존에 남기기로 한 감정"만 원래 속에 남기고,
# 나머지 하나씩을 새 속으로 분리 독립시킨다. 즐거움->생동은 원래도 대분류 하나가 속 하나에
# 그대로 대응했으니 그대로 둔다.
